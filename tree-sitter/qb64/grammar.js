/**
 * Tree-sitter grammar for QB64-PE (Phoenix Edition).
 *
 * The grammar is deliberately permissive: QB64-PE has a very large and
 * evolving command set, so anything that is not recognised is still parsed
 * safely as an identifier instead of producing error nodes.
 *
 * Keyword lists are derived from the QB64PE language data used by the
 * reference VS Code extension (grymmjack/qb64pe-vscode), so highlighting
 * covers the same vocabulary.
 */

// Case-insensitive literal: turn "PRINT" into /[Pp][Rr][Ii][Nn][Tt]/.
const kw = (s) => {
  const escaped = s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return new RegExp(
    escaped.replace(
      /[A-Za-z]/g,
      (c) => `[${c.toLowerCase()}${c.toUpperCase()}]`,
    ),
  );
};


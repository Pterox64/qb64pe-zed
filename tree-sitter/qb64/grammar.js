// Data types highlighted separately from other keywords.
const TYPE_KEYWORDS = new Set([
  "ANY",
  "BYTE",
  "WORD",
  "INTEGER",
  "LONG",
  "SINGLE",
  "DOUBLE",
  "STRING",
  "UNSIGNED",
  "INTEGER64",
  "CUSTOMTYPE",
  "_BYTE",
  "_WORD",
  "_INTEGER",
  "_INTEGER64",
  "_UNSIGNED",
  "_UNSIGNED64",
  "_FLOAT",
  "_OFFSET",
  "_MEM",
]);

const typeKeywords = ALL_KEYWORDS.filter((k) => TYPE_KEYWORDS.has(k));
const builtins = ALL_KEYWORDS.filter(
  (k) => k.startsWith("_") && !TYPE_KEYWORDS.has(k),
);
const keywords = ALL_KEYWORDS.filter(
  (k) => !k.startsWith("_") && !k.startsWith("$") && !TYPE_KEYWORDS.has(k),
);

module.exports = grammar({
  name: "qb64",

  extras: ($) => [/[ \t]/],

  word: ($) => $.identifier,

  rules: {
    source_file: ($) =>
      repeat(
        choice(
          $.comment,
          $.metacommand,
          $.string,
          $.number,
          $.keyword,
          $.builtin,
          $.type_keyword,
          $.identifier,
          $.operator,
          $.label,
          $._bracket,
          $.punctuation,
          $.newline,
        ),
      ),

    comment: (_) => token(choice(/'[^\r\n]*/, /[Rr][Ee][Mm][ \t][^\r\n]*/)),

    // `$CONSOLE`, `$IF`, `'$INCLUDE:'file.bi'`, `$VERSIONINFO:...`.
    // Higher precedence than `comment` so a quoted metacommand is not
    // swallowed as a comment.
    metacommand: (_) =>
      token(prec(2, /'?\$[A-Za-z_][A-Za-z0-9_]*(?::[^\r\n]*)?/)),

    string: (_) => /"(?:[^"\r\n]|"")*"/,

    number: (_) =>
      token(
        choice(
          /&[Hh][0-9A-Fa-f]+/,
          /&[Oo][0-7]+/,
          /(?:[0-9]+(?:\.[0-9]*)?|\.[0-9]+)(?:[EeDd][+-]?[0-9]+)?(?:[!#%&])?/,
        ),
      ),

    keyword: (_) => token(choice(...keywords.map(kw))),

    builtin: (_) => token(choice(...builtins.map(kw))),

    type_keyword: (_) => token(choice(...typeKeywords.map(kw))),

    identifier: (_) => /[A-Za-z_][A-Za-z0-9_]*(?:~?(?:%%|&&|##|[%&!#`])|\$)?/,

    label: (_) => /[A-Za-z_][A-Za-z0-9_]*:/,

    operator: (_) => token(/<>|<=|>=|==|=|<|>|\+|-|\*|\/|\\|\^/),

    // Brackets are individual anonymous tokens so that `brackets.scm` can
    // pair them (rainbow brackets / bracket matching in Zed).
    _bracket: (_) => choice("(", ")", "[", "]"),

    punctuation: (_) => /[.,:;]/,

    newline: (_) => /\r?\n/,
  },
});
